/**
 * Copy the FFmpeg.wasm core and worker into public/ffmpeg so everything is
 * served from the app's own origin (no CDN, no COOP/COEP headers needed).
 *
 * The worker is bundled with esbuild into a single classic script because the
 * published ESM worker uses relative imports that do not survive being served
 * as a static file. Runs after `npm install` and via `npm run setup:ffmpeg`.
 */
import { build } from "esbuild";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const coreSrc = join(root, "node_modules", "@ffmpeg", "core", "dist", "umd");
const workerEntry = join(root, "node_modules", "@ffmpeg", "ffmpeg", "dist", "esm", "worker.js");
const libSrc = join(root, "node_modules", "@ffmpeg", "ffmpeg", "dist", "umd", "ffmpeg.js");
const dest = join(root, "public", "ffmpeg");
// Fall back to the committed copy when node_modules is not present (CI, fresh clone).
const libFallback = join(dest, "ffmpeg.js");

if (!existsSync(coreSrc) || !existsSync(workerEntry)) {
  console.warn("[setup:ffmpeg] @ffmpeg packages are not installed - keeping committed assets");
  process.exit(0);
}
mkdirSync(dest, { recursive: true });

for (const file of ["ffmpeg-core.js", "ffmpeg-core.wasm"]) {
  copyFileSync(join(coreSrc, file), join(dest, file));
  console.log(`[setup:ffmpeg] ${file} -> public/ffmpeg/`);
}
// The UMD build hard-codes its build-time path in `new URL(..., import.meta.url)`.
// A Blob worker inherits that URL, so a relative resolution can never succeed.
// An absolute URL (set at runtime from window.location) makes it moot.
const source = readFileSync(existsSync(libSrc) ? libSrc : libFallback, "utf8");
const patched = source
  // The library always asks for a *module* worker; module workers cannot
  // importScripts(), which the FFmpeg core loader relies on. Drop the options.
  .replace(
    /new Worker\(new URL\(s,"file:\/\/\/[^"]*"\)/g,
    "new Worker(s",
  )
  .replace(
    /new Worker\(new URL\(s,"https:\/\/localhost\.invalid\/ffmpeg-worker\.js"\)/g,
    "new Worker(s",
  )
  // The fallback (no classWorkerURL) must resolve against the page, not a baked path.
  .replace(
    /new Worker\(new URL\(e\.p\+e\.u\(814\),e\.b\)/g,
    "new Worker(new URL(e.p+e.u(814),location.href)",
  );

if (!/new Worker\(s\)/.test(patched)) {
  throw new Error("[setup:ffmpeg] could not patch the worker constructor - check the @ffmpeg/ffmpeg version");
}
writeFileSync(join(dest, "ffmpeg.js"), patched);
console.log("[setup:ffmpeg] ffmpeg.js (UMD library, worker base patched) -> public/ffmpeg/");

await build({
  entryPoints: [workerEntry],
  bundle: true,
  format: "iife",
  target: "es2022",
  outfile: join(dest, "ffmpeg-worker.js"),
  logLevel: "silent",
});
console.log("[setup:ffmpeg] ffmpeg-worker.js -> public/ffmpeg/");

// Sanity check: the bundle must not import anything at runtime.
const bundled = readFileSync(join(dest, "ffmpeg-worker.js"), "utf8");
if (/\bfrom\s*"\.\//.test(bundled)) {
  console.warn("[setup:ffmpeg] warning: bundled worker still contains relative imports");
}
writeFileSync(join(dest, ".ok"), "generated by scripts/setup-ffmpeg.mjs\n");
